"""Build the MiniMax TTS training corpus -- template-free, bilingual version.

The first version of this generator was combinatorial: every room x device pair
produced the same sentence shape, and every number produced a variant of three
stock frames. A cloned voice then hears "今天气温X度，出门记得带件外套。" twenty-one
times and learns the template instead of the language.

Rules this version enforces (verified by ``scripts/check_corpus.py``):

* every line is unique,
* no two lines share the same opening ``FRAME`` characters,
* generated lists mix several sentence shapes and hand-written lines so no
  frame repeats,
* every Chinese line is 8-25 characters and ends in punctuation,
* the polyphonic and tone-change lists cover their target readings.

Categories are written in JSONL order, so a prefix of the corpus stays balanced:

    special, polyphonic, tone_change, numbers, home, daily, anime, literary,
    reading, mixed

``mixed`` carries the English: pure English lines, code-switched lines and a few
thousand characters of pure Chinese so the two languages stay in proportion. See
``scripts/bilingual_corpus.py`` for why a Chinese Piper voice can be fine-tuned
on English at all, and ``scripts/phonemize_bilingual.py`` for what has to change
at synthesis time.

Run:  .venv/Scripts/python.exe scripts/make_corpus.py
"""

