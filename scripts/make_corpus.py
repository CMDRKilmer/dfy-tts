def cn(n: int) -> str:
    """0-99 in Mandarin, the way people say small numbers."""
    if n < 10:
        return DIGITS[n]
    if n == 10:
        return "十"
    if n < 20:
        return "十" + DIGITS[n % 10]
    tens, ones = divmod(n, 10)
    return DIGITS[tens] + "十" + (DIGITS[ones] if ones else "")


