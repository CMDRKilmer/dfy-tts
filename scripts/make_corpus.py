def split_lines(text: str) -> list[str]:
    return [l.strip() for l in text.split("\n") if l.strip()]


def dedupe_lines(lines: list[str]) -> list[str]:
    """Drop exact repeats while keeping the original order."""
    seen: set[str] = set()
    out = []
    for line in lines:
        if line in seen:
            continue
        seen.add(line)
        out.append(line)
    return out


def build_polyphonic() -> list[str]:
    """Lines whose target character appears in several of its readings.

    ``POLYPHONIC`` entries are ``(target, readings, line)`` -- the second slot is
    annotation for human review, never spoken.
    """
    return [line for _target, _readings, line in POLYPHONIC]


def build_tone_change() -> list[str]:
    """Lines covering neutral tone, erhua, tone sandhi and 啊 allomorphs."""
    lines: list[str] = []
    for _family, members in TONE_CHANGE:
        lines.extend(members)
    return lines


def build_mixed() -> list[str]:
    """English, code-switching and a slice of Chinese to keep the ratio sane."""
    lines: list[str] = []
    for block in (ENGLISH, MIXED_ZH_EN, ZH_ONLY):
        lines.extend(split_lines(block))
    return lines


CJK_RE = re.compile(r"[\u3400-\u4dbf\u4e00-\u9fff\uf900-\ufaff]")
WORD_RE = re.compile(r"[A-Za-z][A-Za-z'\-]*")


def _measure(line: str) -> tuple[int, str]:
    """Return ``(length, unit)`` for a corpus line.

    Pure-English lines count words (``"word"``); anything containing Chinese
    counts characters, with Latin words folded in as their word count so a
    code-switched line is not punished for spelling "air conditioner" out.
    """
    if CJK_RE.search(line):
        chinese = len(CJK_RE.findall(line))
        return chinese + len(WORD_RE.findall(line)), "chars"
    return len(WORD_RE.findall(line)), "words"


def enforce_length(lines: list[str]) -> list[str]:
    """Drop lines outside the 8-25 rule and report how many went.

    Chinese and code-switched lines are bounded by characters, pure-English
    lines by words. 8 characters of Chinese is about two seconds of speech;
    25 English characters would be barely four words, so English gets its own
    window.
    """
    kept: list[str] = []
    dropped = 0
    for line in lines:
        length, unit = _measure(line)
        lo, hi = (MIN_CHARS, MAX_CHARS) if unit == "chars" else (MIN_WORDS, MAX_WORDS)
        if lo <= length <= hi:
            kept.append(line)
        else:
            dropped += 1
    if dropped:
        print(f"  dropped {dropped} line(s) outside the length rule")
    return kept


